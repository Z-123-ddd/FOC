#ifndef __TYPES_H
#define __TYPES_H

#include <stdint.h>

/* 自定义短类型 — 供 MotorControl 库使用 */
typedef  uint8_t          u8;
typedef  uint16_t         u16;
typedef  uint32_t         u32;
typedef  uint64_t         u64;

typedef  int8_t           s8;
typedef  int16_t          s16;
typedef  int32_t          s32;
typedef  signed long long s64;

#endif /* __TYPES_H */
